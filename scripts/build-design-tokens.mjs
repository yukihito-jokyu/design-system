import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

async function readTokenFile(name) {
  return JSON.parse(await readFile(resolve(root, "tokens", name), "utf8"));
}

const foundation = await readTokenFile("foundation.json");
const semantic = await readTokenFile("semantic.json");
const palettes = await readTokenFile("base-themes.json");

const flat = {};

function tokenEntries(values) {
  return Object.entries(values).sort(([left], [right]) => {
    const leftIsIndex = /^\d+$/.test(left);
    const rightIsIndex = /^\d+$/.test(right);
    return Number(leftIsIndex) - Number(rightIsIndex);
  });
}

for (const status of ["decided", "proposed"]) {
  for (const [group, values] of Object.entries(foundation[status])) {
    if (typeof values === "object" && values !== null) {
      for (const [name, value] of tokenEntries(values)) {
        flat[`${group}-${name}`] = value;
      }
    } else {
      flat[group] = values;
    }
  }
}

for (const [role, target] of Object.entries(semantic.roleAliases)) {
  if (!(target in flat)) {
    throw new Error(`Unknown foundation token: ${target}`);
  }
  flat[role] = `var(--ds-${target})`;
}

for (const [paletteName, palette] of Object.entries(palettes)) {
  for (const target of Object.values(semantic.paletteAliases)) {
    if (!(target in palette.colors)) {
      throw new Error(`Palette ${paletteName} is missing color: ${target}`);
    }
  }
}

const css = [
  "/* Generated by scripts/build-design-tokens.mjs. Contains explicitly marked draft values. */",
  ":root, [data-ds-base] {",
  ...Object.entries(flat).map(([key, value]) => `  --ds-${key}: ${value};`),
  "}",
];

for (const [name, palette] of Object.entries(palettes)) {
  const selector = name === "milk" ? `:root, [data-ds-base="${name}"]` : `[data-ds-base="${name}"]`;
  css.push(
    `${selector} {`,
    ...Object.entries(palette.colors).map(([key, value]) => `  --m-${key}: ${value};`),
    "}",
  );
}

// Resolve semantic aliases at each theme boundary, not only the document root.
css.push(
  ":root, [data-ds-base] {",
  ...Object.entries(semantic.paletteAliases).map(
    ([name, target]) => `  --${name}: var(--m-${target});`,
  ),
  ...Object.entries(semantic.statusColors).map(([name, value]) => `  --${name}: ${value};`),
  "  --radius: var(--ds-radius-control);",
  "}",
  "@media (prefers-reduced-motion: reduce) {",
  "  :root, [data-ds-base] {",
  "    --ds-duration-fast: 0ms;",
  "    --ds-duration-normal: 0ms;",
  "    --ds-duration-feedback: 0ms;",
  "    --ds-motion-distance-enter: 0px;",
  "  }",
  "}",
);

const outputDirectory = resolve(root, "registry", "styles");
await mkdir(outputDirectory, { recursive: true });
await writeFile(resolve(outputDirectory, "tokens.css"), `${css.join("\n")}\n`);

// Optional Tailwind v4 bridge. Keep explicit radius values instead of inherited shadcn ratios.
const colors = [
  ...Object.keys(semantic.paletteAliases),
  ...Object.keys(semantic.statusColors).filter((key) => key !== "overlay"),
];

const bridge = [
  "/* Optional Tailwind v4 adapter; load after Tailwind and tokens.css. */",
  "@theme inline {",
  ...colors.map((key) => `  --color-${key}: var(--${key});`),
  ...["sm", "md", "lg", "xl", "pill"].map((key) => `  --radius-${key}: var(--ds-radius-${key});`),
  "  --font-sans: var(--ds-font-family-sans);",
  "  --font-mono: var(--ds-font-family-mono);",
  "}",
];

await writeFile(resolve(outputDirectory, "tailwind.css"), `${bridge.join("\n")}\n`);

console.log(
  "Built shared tokens.css and optional Tailwind adapter for",
  Object.keys(palettes).length,
  "palettes.",
);
